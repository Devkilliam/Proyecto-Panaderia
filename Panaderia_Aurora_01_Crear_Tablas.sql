-- En este archivo creamos las 14 tablas que diseñamos en el primer avance.
-- Definimos los tipos de datos y las restricciones de cada tabla
-- para que nuestro modelo relacional funcione en Oracle.
--
-- Para ejecutar nuestro archivo:
-- 1. Abrimos una hoja SQL con PANADERIA_AURORA, no con SYSTEM.
-- 2. Ejecutamos el archivo completo con F5.
-- 3. Revisamos al final que TOTAL_TABLAS sea igual a 14.
-- 4. No lo repetimos si ya creamos las tablas, porque no las reemplaza.

SET SERVEROUTPUT ON

DECLARE
    v_existentes NUMBER;
BEGIN
    -- Comprobamos que no estemos conectados a SYSTEM ni a otro contenedor.
    IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'PANADERIA_AURORA'
       OR SYS_CONTEXT('USERENV','CON_NAME') <> 'XEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Conexion incorrecta. Usa PANADERIA_AURORA en XEPDB1.');
    END IF;

    SELECT COUNT(*) INTO v_existentes
      FROM USER_TABLES
     WHERE TABLE_NAME IN (
          'CATEGORIA','PRODUCTO','INGREDIENTE','PROVEEDOR',
          'PROVEEDOR_INGREDIENTE','RECETA','RECETA_INGREDIENTE',
          'CLIENTE','EMPLEADO','PEDIDO','DETALLE_PEDIDO',
          'PRODUCCION','VENTA','MOVIMIENTO_INVENTARIO');

    IF v_existentes > 0 THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Hay tablas de Panaderia Aurora existentes (' || v_existentes ||
            '). No se modifico ninguna. Revisar antes de reintentar.');
    END IF;

    -- 01. Organizamos los productos por categorías.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE CATEGORIA (
            id_categoria NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            nombre VARCHAR2(100 CHAR) NOT NULL,
            descripcion VARCHAR2(250 CHAR),
            CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
            CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
        )~';

    -- 02. Guardamos los productos que ofrecemos a nuestros clientes.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE PRODUCTO (
            id_producto NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_categoria NUMBER NOT NULL,
            nombre VARCHAR2(150 CHAR) NOT NULL,
            precio_venta NUMBER(12,2) NOT NULL,
            activo NUMBER(1) DEFAULT 1 NOT NULL,
            CONSTRAINT pk_producto PRIMARY KEY (id_producto),
            CONSTRAINT fk_prod_categoria FOREIGN KEY (id_categoria)
                REFERENCES CATEGORIA(id_categoria),
            CONSTRAINT ck_prod_precio CHECK (precio_venta >= 0),
            CONSTRAINT ck_prod_activo CHECK (activo IN (0,1))
        )~';

    -- 03. Registramos los ingredientes; calculamos su existencia con los movimientos.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE INGREDIENTE (
            id_ingrediente NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            nombre VARCHAR2(150 CHAR) NOT NULL,
            unidad_medida VARCHAR2(30 CHAR) NOT NULL,
            stock_minimo NUMBER(12,3) DEFAULT 0 NOT NULL,
            CONSTRAINT pk_ingrediente PRIMARY KEY (id_ingrediente),
            CONSTRAINT ck_ing_stock CHECK (stock_minimo >= 0)
        )~';

    -- 04. Guardamos la información de nuestros proveedores.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE PROVEEDOR (
            id_proveedor NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            nombre VARCHAR2(150 CHAR) NOT NULL,
            telefono VARCHAR2(25 CHAR),
            correo VARCHAR2(150 CHAR),
            CONSTRAINT pk_proveedor PRIMARY KEY (id_proveedor)
        )~';

    -- 05. Relacionamos los proveedores con los ingredientes que suministran.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE PROVEEDOR_INGREDIENTE (
            id_proveedor NUMBER NOT NULL,
            id_ingrediente NUMBER NOT NULL,
            costo_referencial NUMBER(12,2),
            CONSTRAINT pk_prov_ing PRIMARY KEY (id_proveedor,id_ingrediente),
            CONSTRAINT fk_pi_proveedor FOREIGN KEY (id_proveedor)
                REFERENCES PROVEEDOR(id_proveedor),
            CONSTRAINT fk_pi_ingrediente FOREIGN KEY (id_ingrediente)
                REFERENCES INGREDIENTE(id_ingrediente),
            CONSTRAINT ck_pi_costo CHECK (costo_referencial >= 0)
        )~';

    -- 06. Registramos las recetas y sus versiones para cada producto.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE RECETA (
            id_receta NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_producto NUMBER NOT NULL,
            version_receta NUMBER(5) DEFAULT 1 NOT NULL,
            rendimiento NUMBER(12,3) NOT NULL,
            CONSTRAINT pk_receta PRIMARY KEY (id_receta),
            CONSTRAINT fk_rec_producto FOREIGN KEY (id_producto)
                REFERENCES PRODUCTO(id_producto),
            CONSTRAINT uq_rec_version UNIQUE (id_producto,version_receta),
            CONSTRAINT ck_rec_version CHECK (version_receta > 0),
            CONSTRAINT ck_rec_rendimiento CHECK (rendimiento > 0)
        )~';

    -- 07. Indicamos qué ingredientes y cantidades lleva cada receta.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE RECETA_INGREDIENTE (
            id_receta NUMBER NOT NULL,
            id_ingrediente NUMBER NOT NULL,
            cantidad_requerida NUMBER(12,3) NOT NULL,
            CONSTRAINT pk_rec_ing PRIMARY KEY (id_receta,id_ingrediente),
            CONSTRAINT fk_ri_receta FOREIGN KEY (id_receta)
                REFERENCES RECETA(id_receta),
            CONSTRAINT fk_ri_ingrediente FOREIGN KEY (id_ingrediente)
                REFERENCES INGREDIENTE(id_ingrediente),
            CONSTRAINT ck_ri_cantidad CHECK (cantidad_requerida > 0)
        )~';

    -- 08. Registramos los datos de nuestros clientes.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE CLIENTE (
            id_cliente NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            nombre VARCHAR2(150 CHAR) NOT NULL,
            telefono VARCHAR2(25 CHAR),
            correo VARCHAR2(150 CHAR),
            CONSTRAINT pk_cliente PRIMARY KEY (id_cliente)
        )~';

    -- 09. Registramos los datos de los empleados.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE EMPLEADO (
            id_empleado NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            nombre VARCHAR2(150 CHAR) NOT NULL,
            rol VARCHAR2(80 CHAR) NOT NULL,
            CONSTRAINT pk_empleado PRIMARY KEY (id_empleado)
        )~';

    -- 10. Guardamos la información general de cada pedido.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE PEDIDO (
            id_pedido NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_cliente NUMBER NOT NULL,
            id_empleado NUMBER NOT NULL,
            fecha_pedido DATE DEFAULT SYSDATE NOT NULL,
            fecha_entrega DATE,
            tipo VARCHAR2(40 CHAR) DEFAULT 'MOSTRADOR' NOT NULL,
            estado VARCHAR2(30 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
            CONSTRAINT pk_pedido PRIMARY KEY (id_pedido),
            CONSTRAINT fk_ped_cliente FOREIGN KEY (id_cliente)
                REFERENCES CLIENTE(id_cliente),
            CONSTRAINT fk_ped_empleado FOREIGN KEY (id_empleado)
                REFERENCES EMPLEADO(id_empleado),
            CONSTRAINT ck_ped_estado CHECK (estado IN (
                'PENDIENTE','EN_PRODUCCION','LISTO','ENTREGADO','CANCELADO'))
        )~';

    -- 11. Detallamos los productos y las cantidades de cada pedido.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE DETALLE_PEDIDO (
            id_detalle NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_pedido NUMBER NOT NULL,
            id_producto NUMBER NOT NULL,
            cantidad NUMBER(10) NOT NULL,
            precio_unitario NUMBER(12,2) NOT NULL,
            CONSTRAINT pk_det_pedido PRIMARY KEY (id_detalle),
            CONSTRAINT fk_dp_pedido FOREIGN KEY (id_pedido)
                REFERENCES PEDIDO(id_pedido),
            CONSTRAINT fk_dp_producto FOREIGN KEY (id_producto)
                REFERENCES PRODUCTO(id_producto),
            CONSTRAINT uq_dp_prod UNIQUE (id_pedido,id_producto),
            CONSTRAINT ck_dp_cantidad CHECK (cantidad > 0),
            CONSTRAINT ck_dp_precio CHECK (precio_unitario >= 0)
        )~';

    -- 12. Llevamos el control de los lotes producidos y sus responsables.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE PRODUCCION (
            id_produccion NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_receta NUMBER NOT NULL,
            id_empleado NUMBER NOT NULL,
            fecha_produccion DATE DEFAULT SYSDATE NOT NULL,
            lotes_producidos NUMBER(10) NOT NULL,
            estado VARCHAR2(30 CHAR) DEFAULT 'PLANIFICADA' NOT NULL,
            CONSTRAINT pk_produccion PRIMARY KEY (id_produccion),
            CONSTRAINT fk_pro_receta FOREIGN KEY (id_receta)
                REFERENCES RECETA(id_receta),
            CONSTRAINT fk_pro_empleado FOREIGN KEY (id_empleado)
                REFERENCES EMPLEADO(id_empleado),
            CONSTRAINT ck_pro_lotes CHECK (lotes_producidos > 0),
            CONSTRAINT ck_pro_estado CHECK (estado IN (
                'PLANIFICADA','EN_PROCESO','COMPLETADA','CANCELADA'))
        )~';

    -- 13. Asociamos cada venta con el pedido que atendimos.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE VENTA (
            id_venta NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_pedido NUMBER NOT NULL,
            fecha_venta DATE DEFAULT SYSDATE NOT NULL,
            medio_pago VARCHAR2(50 CHAR) NOT NULL,
            CONSTRAINT pk_venta PRIMARY KEY (id_venta),
            CONSTRAINT fk_ven_pedido FOREIGN KEY (id_pedido)
                REFERENCES PEDIDO(id_pedido),
            CONSTRAINT uq_ven_pedido UNIQUE (id_pedido)
        )~';

    -- 14. Anotamos los movimientos de inventario relacionados con compras y producción.
    EXECUTE IMMEDIATE q'~
        CREATE TABLE MOVIMIENTO_INVENTARIO (
            id_movimiento NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            id_ingrediente NUMBER NOT NULL,
            id_empleado NUMBER NOT NULL,
            id_proveedor NUMBER,
            id_produccion NUMBER,
            tipo VARCHAR2(30 CHAR) NOT NULL,
            cantidad NUMBER(12,3) NOT NULL,
            fecha_movimiento DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT pk_mov_inv PRIMARY KEY (id_movimiento),
            CONSTRAINT fk_mi_ingrediente FOREIGN KEY (id_ingrediente)
                REFERENCES INGREDIENTE(id_ingrediente),
            CONSTRAINT fk_mi_empleado FOREIGN KEY (id_empleado)
                REFERENCES EMPLEADO(id_empleado),
            CONSTRAINT fk_mi_proveedor FOREIGN KEY (id_proveedor)
                REFERENCES PROVEEDOR(id_proveedor),
            CONSTRAINT fk_mi_produccion FOREIGN KEY (id_produccion)
                REFERENCES PRODUCCION(id_produccion),
            CONSTRAINT ck_mi_tipo CHECK (tipo IN (
                'ENTRADA','SALIDA','AJUSTE_ENTRADA','AJUSTE_SALIDA')),
            CONSTRAINT ck_mi_cantidad CHECK (cantidad > 0)
        )~';

    DBMS_OUTPUT.PUT_LINE('Tablas creadas. Revisar los resultados siguientes.');
END;
