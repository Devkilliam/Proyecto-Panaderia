WHERE TABLE_NAME IN (
    'CATEGORIA','PRODUCTO','INGREDIENTE','PROVEEDOR',
    'PROVEEDOR_INGREDIENTE','RECETA','RECETA_INGREDIENTE',
    'CLIENTE','EMPLEADO','PEDIDO','DETALLE_PEDIDO',
    'PRODUCCION','VENTA','MOVIMIENTO_INVENTARIO');

